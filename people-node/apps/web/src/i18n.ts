/** Shared UI copy shape — values differ by locale, keys must match `i18n.en`. */
export type Translation = { [K in keyof typeof i18n.en]: string };

export function labelValidatorStatus(t: Translation, status: string): string {
  switch (status) {
    case "joining":
      return t.statusJoining;
    case "active":
      return t.statusActive;
    case "inactive":
      return t.statusInactive;
    case "slashed":
      return t.statusSlashed;
    case "unbonding":
      return t.statusUnbonding;
    default:
      return status;
  }
}

export function labelTxType(t: Translation, type: string): string {
  switch (type) {
    case "transfer":
      return t.txTypeTransfer;
    case "joinValidator":
      return t.txTypeJoinValidator;
    case "leaveValidator":
      return t.txTypeLeaveValidator;
    case "unstake":
      return t.txTypeUnstake;
    case "attestation":
      return t.txTypeAttestation;
    case "slashEvidence":
      return t.txTypeSlashEvidence;
    case "proposal":
      return t.txTypeProposal;
    case "vote":
      return t.txTypeVote;
    default:
      return type;
  }
}

export function labelNodeKind(t: Translation, kind: string): string {
  if (kind === "full") {
    return t.nodeKindFullShort;
  }
  if (kind === "light") {
    return t.nodeKindLightShort;
  }
  return kind;
}

export function labelProposalStatus(t: Translation, status: string): string {
  switch (status) {
    case "open":
      return t.proposalStatusOpen;
    case "passed":
      return t.proposalStatusPassed;
    case "rejected":
      return t.proposalStatusRejected;
    default:
      return status;
  }
}

export function detectInitialLanguage(): Language {
  const stored = localStorage.getItem(LANGUAGE_KEY);
  if (stored === "en" || stored === "ru") {
    return stored;
  }
  const browserLang = navigator.language.toLowerCase();
  return browserLang.startsWith("ru") ? "ru" : "en";
}

export function detectInitialTheme(): Theme {
  const stored = localStorage.getItem(THEME_KEY);
  if (stored === "light" || stored === "dark") {
    return stored;
  }
  return "light";
}
